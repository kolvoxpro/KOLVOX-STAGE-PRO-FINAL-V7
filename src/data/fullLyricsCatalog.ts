export function findVerifiedFullLyrics(title: string, artist?: string): VerifiedSongLyric | null {
  const cleanStr = (s: string) =>
    s
      .toLowerCase()
      .normalize("NFD")
      .replace(/[\u0300-\u036f]/g, "")
      .replace(/[^a-z0-9]/g, "");

  const normTitle = cleanStr(title);
  const normArtist = artist ? cleanStr(artist) : "";

  // 1. Direct match title + artist
  const exact = VERIFIED_FULL_LYRICS.find((s) => {
    const sTitle = cleanStr(s.title);
    const sArtist = cleanStr(s.artist);
    const titleMatches = sTitle === normTitle || sTitle.includes(normTitle) || normTitle.includes(sTitle);
    if (!normArtist) return titleMatches;
    const artistMatches = sArtist.includes(normArtist) || normArtist.includes(sArtist);
    return titleMatches && artistMatches;
  });
  if (exact) return exact;

  // 2. If artist provided, never return another artist song!
  if (normArtist) {
    const artistMatch = VERIFIED_FULL_LYRICS.find((s) => {
      const sArtist = cleanStr(s.artist);
      const sTitle = cleanStr(s.title);
      return (
        (sArtist.includes(normArtist) || normArtist.includes(sArtist)) &&
        (sTitle.includes(normTitle) || normTitle.includes(sTitle))
      );
    });
    if (artistMatch) return artistMatch;
    return null;
  }

  // 3. Fallback only if no artist specified
  const titleOnly = VERIFIED_FULL_LYRICS.find((s) => {
    const sTitle = cleanStr(s.title);
    return sTitle === normTitle;
  });
  return titleOnly || null;
}
